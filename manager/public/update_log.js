  function renderLogSectionsHtml(entry, { compact = false } = {}) {
    const features = Array.isArray(entry?.features) ? entry.features : [];
    const fixes = Array.isArray(entry?.fixes) ? entry.fixes : [];
    let html = renderUiPreviewsGalleryHtml(entry, compact);

    if (features.length > 0) {
      html += `
        <div class="ulog-section-box" style="border-color: rgba(52, 211, 153, 0.28);">
          <div class="ulog-section-title" style="color: #34d399;">✨ ทำอะไรได้บ้าง (ฟีเจอร์ & ความสามารถใหม่)</div>
          <ul class="ulog-list">
            ${features.map(item => `<li>${formatUpdateText(item)}</li>`).join('')}
          </ul>
        </div>
      `;
    }
    if (fixes.length > 0) {
      html += `
        <div class="ulog-section-box" style="border-color: rgba(56, 189, 248, 0.28);">
          <div class="ulog-section-title" style="color: #38bdf8;">🛠️ แก้อะไรบ้าง (ปรับปรุง & แก้ไขบั๊ก)</div>
          <ul class="ulog-list">
            ${fixes.map(item => `<li>${formatUpdateText(item)}</li>`).join('')}
          </ul>
        </div>
      `;
    }
    return html;
  }

