  const STORAGE_KEY_SEEN_VER = 'pmheenc_seen_update_log_ver';

  function escapeHtml(str) {
    return String(str || '')
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  function formatUpdateText(text) {
    return escapeHtml(text)
      .replace(/\*\*(.+?)\*\*/g, '<strong style="color:#f8fafc;">$1</strong>')
      .replace(/`([^`]+)`/g, '<code style="background:rgba(56,189,248,0.14);color:#7dd3fc;padding:1px 5px;border-radius:4px;font-size:11px;">$1</code>');
  }

  function getLatestLog() {
    return UPDATE_LOGS[0] || null;
  }

  function isLatestSeen() {
    const latest = getLatestLog();
    if (!latest) return true;
    try {
      return localStorage.getItem(STORAGE_KEY_SEEN_VER) === latest.version;
    } catch (e) {
      return false;
    }
  }

  function markLatestSeen() {
    const latest = getLatestLog();
    if (!latest) return;
    try {
      localStorage.setItem(STORAGE_KEY_SEEN_VER, latest.version);
    } catch (e) {}
    updateHeaderBadge();
  }

